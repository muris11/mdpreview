import DOMPurify from 'dompurify'

const SVG_TAGS = [
  'svg',
  'g',
  'path',
  'rect',
  'circle',
  'ellipse',
  'line',
  'polyline',
  'polygon',
  'text',
  'tspan',
  'defs',
  'marker',
  'clipPath',
  'use',
  'symbol',
  'linearGradient',
  'radialGradient',
  'stop',
  'pattern',
  'filter',
  'feGaussianBlur',
  'feOffset',
  'feBlend',
  'feColorMatrix',
  'foreignObject',
  'title',
  'desc',
  'style',
]

const MATHML_TAGS = [
  'math',
  'semantics',
  'annotation',
  'mrow',
  'mi',
  'mo',
  'mn',
  'msup',
  'msub',
  'msubsup',
  'mfrac',
  'msqrt',
  'mroot',
  'mtext',
  'mspace',
  'mover',
  'munder',
  'munderover',
  'ms',
  'mtable',
  'mtr',
  'mtd',
  'mstyle',
  'mpadded',
  'mphantom',
  'menclose',
  'mstack',
  'mlongdiv',
  'msgroup',
  'msrow',
  'mscarries',
  'mscarry',
  'msline',
  'maligngroup',
  'malignmark',
  'annotation-xml',
]

export function sanitize(html: string): string {
  return DOMPurify.sanitize(html, {
    ADD_TAGS: [...SVG_TAGS, ...MATHML_TAGS],
    ADD_ATTR: [
      'target',
      'rel',
      'id',
      'class',
      'style',
      'aria-hidden',
      'aria-label',
      'focusable',
      'viewBox',
      'xmlns',
      'xmlns:xlink',
      'xlink:href',
      'preserveAspectRatio',
      'd',
      'fill',
      'fill-opacity',
      'fill-rule',
      'stroke',
      'stroke-width',
      'stroke-linecap',
      'stroke-linejoin',
      'stroke-dasharray',
      'stroke-opacity',
      'transform',
      'x',
      'y',
      'x1',
      'y1',
      'x2',
      'y2',
      'cx',
      'cy',
      'r',
      'rx',
      'ry',
      'points',
      'width',
      'height',
      'offset',
      'marker-end',
      'marker-start',
      'marker-mid',
      'text-anchor',
      'dominant-baseline',
      'font-size',
      'font-family',
      'font-weight',
      'font-style',
      'letter-spacing',
      'mathvariant',
      'encoding',
      'display',
      'overflow',
    ],
    ALLOW_DATA_ATTR: true,
  })
}
